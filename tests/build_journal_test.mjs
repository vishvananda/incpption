import assert from 'node:assert/strict';
import {BuildJournal} from '../web/build_journal.mjs';
const values=new Map(),store={getItem:key=>values.get(key),setItem:(key,value)=>values.set(key,value),removeItem:key=>values.delete(key)};
let time=0;
const first=new BuildJournal(store,()=>time);
first.update('game',{project:'doom',step:'one.cpp'},true);
first.update('game-clang',{project:'doom',step:'two.cpp'},true);
time=100;first.update('game-clang',{project:'doom',step:'three.cpp'});
assert.equal(JSON.parse([...values.values()][0]).phases[1].step,'two.cpp','every progress message wrote synchronous storage');
time=1100;first.update('game-clang',{project:'doom',step:'four.cpp'});
const restored=new BuildJournal(store,()=>time);
assert.equal(restored.previous.phases[1].step,'four.cpp');assert.equal(restored.previous.phases.length,2);
assert.equal(new BuildJournal(store).previous,undefined,'an old interrupted run appeared twice');
restored.update('game',{step:'file.cpp'},true);restored.update('game-clang',{step:'other.cpp'},true);
restored.finish('game');assert.equal(JSON.parse([...values.values()][0]).phases.length,1);
restored.finish('game-clang');assert.equal(values.size,0,'completed/cancelled builds left an interruption marker');
const blocked={getItem(){throw Error('Blocked');},setItem(){throw Error('Quota');},removeItem(){throw Error('Blocked');}};
const unavailable=new BuildJournal(blocked);unavailable.update('game',{step:'test'},true);unavailable.finish('game');
console.log('PASS: interrupted builds retain both lanes, writes are bounded, completion clears markers, unavailable storage is harmless');
