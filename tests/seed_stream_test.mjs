import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import wabtFactory from 'wabt';
import {compileSeed} from '../web/seed_package.mjs';
const wabt = await wabtFactory(), wat = wabt.parseWat('seed.wat', '(module (func (export "answer") (result i32) i32.const 37))');
const bytes = wat.toBinary({}).buffer; wat.destroy();
const hash = data => createHash('sha256').update(data).digest('hex');
const parts = [bytes.slice(0, 3), bytes.slice(3, 17), bytes.slice(17)];
const tool = {bytes: bytes.length, sha256: hash(bytes), chunks: parts.map((part, i) => ({path:`part${i}.bin`, size:part.length, sha256:hash(part)}))};
const requested = [];
globalThis.fetch = async url => {requested.push(url); return new Response(parts[Number(url.match(/part(\d+)/)[1])]);};
const module = await compileSeed(tool);
assert.equal(new WebAssembly.Instance(module).exports.answer(), 37);
assert.equal(requested.length, parts.length);
await assert.rejects(compileSeed({...tool, sha256:'0'.repeat(64)}), /Compiler seed changed/);
await assert.rejects(compileSeed({...tool, chunks:tool.chunks.map((r,i)=>i===1?{...r,sha256:'0'.repeat(64)}:r)}), /chunk changed/);
await assert.rejects(compileSeed({...tool, bytes:bytes.length+1}), /Incomplete/);
await assert.rejects(compileSeed({...tool, chunks:[{...tool.chunks[0],path:'../escape.bin'}]}), /Invalid/);
console.log('PASS: streamed Wasm compiles across chunk boundaries and rejects changed chunks, whole-file hashes and invalid sizes');
