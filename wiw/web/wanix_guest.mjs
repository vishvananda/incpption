const decoder = new TextDecoder();
const delay = () => new Promise(resolve => setTimeout(resolve, 20));
const source = workspace + '/source', shared = 'guest/wiw/';
const names = new Set([...compilerNames, 'ar', 'ranlib']);

function script(config, wasi) {
  const cwd = absolute(source, config.sourceDirectory ?? '.');
  if (cwd !== source && !cwd.startsWith(source + '/')) throw Error('Invalid build directory.');
  const options = config.options ?? [], targets = config.target ? [config.target] : [];
  const make = values => command(['make', '-j1', ...values, ...targets]);
  const build = workspace + '/build';
  const ninja = command(['ninja', '-C', build, '-j1', ...targets]);
  const cmakeArgs = [
    '/usr/bin/cmake', '-S', cwd, '-B', build, '-G', 'Ninja',
    '-DCMAKE_BUILD_TYPE=Release', '-DCMAKE_C_FLAGS_RELEASE=-O3 -DNDEBUG',
    '-DCMAKE_CXX_FLAGS_RELEASE=-O3 -DNDEBUG',
    '-DCMAKE_TOOLCHAIN_FILE=/wiw/' + (wasi ? 'wasi' : 'linux') + '_toolchain.cmake',
    ...(wasi ? ['-DCMAKE_USER_MAKE_RULES_OVERRIDE=/wiw/Platform/WASI.cmake'] : []),
    ...options,
  ];
  const record = 'touch /wiw/recording';
  const phase = "printf '%s\\n' configure > /wiw/phase";
  const setup = command(['sh', './configure', ...options]);
  const configure = [phase, !wasi && !options.some(arg => /^--(?:host|build)(?:=|$)/.test(arg)) ?
    `if grep -q 'Generated by GNU Autoconf' configure; then
  ${setup} --build=i686-pc-linux-musl --host=${linuxTarget}
else
  ${setup}
fi` : setup, record, make([])].join('\n');
  const needsAlpine = "echo 'This build system needs the Alpine guest.' >&2; exit 1";
  const commands = {
    configure,
    make:[record, make(options)].join('\n'),
    cmake:[phase, command(cmakeArgs), record, ninja].join('\n'),
    meson:needsAlpine,
    python:needsAlpine,
  };
  const candidates = [
    ...(wasi ? [['cmake', ['CMakeLists.txt']], ['configure', ['configure']]] :
      [['configure', ['configure']], ['cmake', ['CMakeLists.txt']]]),
    ['meson', ['meson.build']], ['make', makefiles], ['python', ['configure.py']],
  ];
  const auto = candidates.map(([system, files], i) =>
    (i ? 'elif ' : 'if ') + files.map(name => '[ -f ' + quote(name) + ' ]').join(' || ') +
    '; then\n' + commands[system]).join('\n') + '\nelse\n  echo "No supported build system found." >&2\n  exit 1\nfi';
  if (config.system !== 'auto' && !Object.hasOwn(commands, config.system)) throw Error('Unsupported Wanix build system.');
  const sysroot = wasi ? sdkRoot + '/sysroot' : linuxRoot;
  const triplet = wasi ? 'wasm32-wasip1' : linuxTarget;
  return `set -eu
export SOURCE_DATE_EPOCH=${sourceDateEpoch} CC=cc CXX=c++ AR=ar RANLIB=ranlib CHOST=${triplet}
export PKG_CONFIG_PATH= PKG_CONFIG_SYSROOT_DIR=${sysroot} PKG_CONFIG_LIBDIR=${sysroot}/usr/lib/pkgconfig:${sysroot}/share/pkgconfig
mkdir -p /tmp/incpption/bin
for tool in cc c++ ar ranlib; do ln -s /usr/bin/"$tool" /tmp/incpption/bin/"$tool"; done
cd ${quote(cwd)}
${config.system === 'auto' ? auto : commands[config.system]}
`;
}

async function asset(url, expected) {
  const response = await fetch(url);
  if (!response.ok) throw Error('Could not download Wanix ' + url.pathname.split('/').at(-1));
  const bytes = new Uint8Array(await response.arrayBuffer());
  if (await hash(bytes) !== expected) throw Error('Wanix asset checksum differs: ' + url.pathname);
  return bytes;
}

async function guest(runtime) {
  const root = new URL(runtime.root, import.meta.url);
  const load = name => asset(new URL(name, root), runtime.sha256[name]);
  const [kernel, v86, image] = await Promise.all([
    load('kernel.bin'), load('v86.tgz'), Promise.all((runtime.chunks ?? ['linux.tgz']).map(load)),
  ]);
  const url = (parts, type) => URL.createObjectURL(new Blob(parts, {type}));
  const wasm = await new Response(new Blob([kernel]).stream().pipeThrough(new DecompressionStream('gzip'))).arrayBuffer();
  const namespace = document.createElement('wanix-namespace');
  namespace.setAttribute('wasm', url([wasm], 'application/wasm'));
  for (const [dst, bytes] of [['guest', image], ['#vm/v86', [v86]]]) {
    const bind = document.createElement('wanix-bind');
    bind.setAttribute('type', 'archive');
    bind.setAttribute('dst', dst);
    bind.setAttribute('src', url(bytes, 'application/gzip'));
    namespace.append(bind);
  }
  // The v86 loader reads its kernel before the guest's 9P filesystem mounts.
  const boot = document.createElement('wanix-bind');
  boot.setAttribute('src', 'guest/boot');
  boot.setAttribute('dst', 'boot');
  namespace.append(boot);
  const vm = document.createElement('wanix-vm');
  vm.id = 'linux';
  vm.setAttribute('mem', '256M');
  vm.setAttribute('term', '');
  namespace.append(vm);
  const terminal = document.createElement('wanix-term');
  terminal.setAttribute('path', '#vm/linux/term');
  terminal.setAttribute('raw', '');
  namespace.append(terminal);
  const ready = new Promise((resolve, reject) => {
    namespace.addEventListener('ready', resolve, {once:true});
    namespace.addEventListener('error', event => reject(Error(errorText(event.detail?.error ?? event.detail))), {once:true});
  });
  document.body.append(namespace);
  await new Promise((resolve, reject) => {
    const script = document.createElement('script');
    script.type = 'module';
    script.src = new URL('wanix.min.js', root);
    const digest = runtime.sha256['wanix.min.js'];
    script.integrity = 'sha256-' + btoa(String.fromCharCode(...digest.match(/../g).map(hex => parseInt(hex, 16))));
    script.onload = resolve;
    script.onerror = () => reject(Error('Could not load the Wanix runtime.'));
    document.head.append(script);
  });
  await ready;
  while (!vm.term) await delay();
  await vm._nsReady;
  return {fs:namespace.root, vm};
}

async function sample(fs, path, limit) {
  const fd = await fs.open(path);
  try {
    return (await fs.read(fd, limit)) ?? new Uint8Array();
  } finally {
    await fs.close(fd);
  }
}

async function optional(fs, path, limit = 1024) {
  if (!await fs.stat(path).catch(() => null)) return null;
  return sample(fs, path, limit);
}

async function readGuestFile(fs, path) {
  const fd = await fs.open(path);
  const chunks = [];
  let size = 0;
  try {
    for (;;) {
      const bytes = await fs.read(fd, 1024 * 1024);
      if (!bytes?.length) break;
      size += bytes.length;
      if (size > maxWorkspace) throw Error('The configured workspace is too large.');
      chunks.push(bytes);
    }
  } finally {
    await fs.close(fd);
  }
  return new Blob(chunks);
}

function localPath(path) {
  if (!path.startsWith(workspace + '/')) throw Error('Compiler path escapes the Wanix workspace: ' + path);
  return path.slice(workspace.length + 1);
}

async function planner(fs, vm, input, buildTarget, profile, log) {
  let request, inputs, outputs, workspaceError, recording = false, phase = '', lastExitCheck = 0;
  const updateWorkspace = workspaceCache();
  const readWorkspace = async (directory, archive) => {
    const changes = await readGuestFile(fs, directory + archive);
    const removed = await readGuestFile(fs, directory + 'removed.json');
    const stream = changes.stream().pipeThrough(new DecompressionStream('gzip'));
    return updateWorkspace(await boundedBytes(new Response(stream), maxWorkspace), JSON.parse(await removed.text()));
  };
  const readInputs = () => inputs ??= (async () => {
    await fs.writeFile(request + '/snapshot', '1');
    for (;;) {
      const ready = await optional(fs, request + '/inputs.ready');
      if (ready?.at(-1) === 10) {
        if (Number(decoder.decode(ready))) throw Error('Could not snapshot the Wanix workspace for a compiler check.');
        return readWorkspace(request + '/', 'inputs.tar.gz');
      }
      await delay();
    }
  })().catch(error => {
    workspaceError = error;
    throw error;
  });
  const wasi = buildTarget !== linuxTarget;
  const native = wasi ? null : await linuxToolchain(profile, readInputs);
  const [module, layers] = native ? [native.module, native.sdk] : await Promise.all([compiler(profile, true), wasiSdk()]);
  const sdk = native ? layers : layers.map(layer => ({...layer, files:layer.files.map(row =>
    ({...row, path:sdkRoot.slice(1) + '/' + row.path}))}));
  const sysroot = wasi ? sdkRoot : linuxRoot;
  const write = (path, bytes) => outputs.set(localPath(path), bytes);
  const identify = args => {
    if (args.length === 1 && args[0] === '--version') return {stdout:'cppgm (clang-compatible) ' + profile.sdk.gcc + '\n'};
    if (args.some(arg => arg === '-Wl,--version' || arg === '-Wl,-v')) return {stdout:'LLD (Will it Wasm) 20.1.8\n'};
    if (args.includes('-dM') && args.includes('-E') && args.includes('-')) return {stdout:''};
  };
  const trace = toolRelay({
    async read(path) {
      // Ranlib only needs to check that the previously recorded archive exists.
      if (trace.produced.has(path)) return new Uint8Array();
      return (await readInputs()).get(localPath(path));
    },
    write, native, identify,
    async runCompiler({cwd, flags, inputs:sourceFiles, returnBytes}) {
      const tree = mountLayers(sdk);
      for (const [name, bytes] of await readInputs())
        insert(tree, workspace.slice(1) + '/' + name, fileView(bytes));
      let output = flags.lastIndexOf('-o') >= 0 ? flags[flags.lastIndexOf('-o') + 1] : null;
      if (!output && sourceFiles.length && !flags.some(arg => ['-E', '-M', '-MM', '-fsyntax-only'].includes(arg))) {
        const suffix = flags.includes('-c') ? '.o' : flags.includes('-S') ? '.s' : null;
        output = suffix ? sourceFiles[0].split('/').at(-1).replace(/\.[^.]+$/, suffix) : 'a.out';
        flags = [...flags, '-o', output];
      }
      const path = output && output !== '-' ? absolute(cwd, output) : null;
      if (path) localPath(path);
      const result = await invoke(module, tree, flags, sourceDateEpoch, cwd.slice(1), {splitOutput:true});
      const bytes = path && lookup(tree, path.slice(1))?.take();
      if (!returnBytes && !result.status && bytes) write(path, bytes);
      return {exitCode:result.status, stdout:result.stdout, stderr:result.stderr, bytes};
    },
  });
  await fs.writeFile(shared + 'source.tar.gz', input.archive);
  if (['auto', 'cmake'].includes(input.config.system)) {
    // The browser compiler sees the same SDK. The copy in Linux lets build
    // scripts discover headers and libraries without using the guest's ABI.
    const files = (native ? await native.guestFiles() : layers).flatMap(layer => layer.files.map(row =>
      [sysroot.slice('/tmp/'.length) + '/' + row.path, layer.bundle.subarray(row.offset, row.offset + row.size)]));
    const compressed = new Blob([tar(files)]).stream().pipeThrough(new CompressionStream('gzip'));
    await fs.writeFile(shared + 'sdk.tgz', new Uint8Array(await new Response(compressed).arrayBuffer()));
  }
  await fs.writeFile(shared + 'build.sh', script(input.config, wasi));
  log('Starting Wanix Linux.');
  await vm.start();
  for (;;) {
    const done = await optional(fs, shared + 'exit');
    if (done?.at(-1) === 10) {
      const output = decoder.decode(await sample(fs, shared + 'log', 128 * 1024));
      if (output) log(output.trimEnd());
      if (Number(decoder.decode(done))) throw Error('Wanix Linux could not configure and record the build.');
      const files = await readWorkspace(shared, 'workspace.tar.gz');
      const workflow = trace.finish(path => files.has(localPath(path)));
      for (const path of trace.produced) files.delete(localPath(path));
      const snapshot = packWorkspace(new Map([...files].map(([name, bytes]) => [workspace.slice(1) + '/' + name, bytes])));
      return {workflow, snapshot};
    }
    if (performance.now() - lastExitCheck > 1000) {
      lastExitCheck = performance.now();
      const status = await optional(fs, vm.task.path + '/exit');
      if (status && decoder.decode(status).trim()) throw Error('Wanix Linux stopped before the build finished.');
    }
    if (!recording && await optional(fs, shared + 'recording')) {
      recording = true;
      trace.start();
      log('Recording build commands.');
    } else if (!phase && await optional(fs, shared + 'phase')) {
      phase = 'configure';
      log('Running configure.');
    }
    const pending = await optional(fs, shared + 'request');
    if (pending?.at(-1) === 10) {
      const path = decoder.decode(pending).trim();
      if (!/^\/wiw\/call-\d+$/.test(path)) throw Error('Invalid Wanix compiler request.');
      request = 'guest' + path;
      const args = await sample(fs, request + '/args', 128 * 1024 + 1);
      const fields = decoder.decode(args).split('\0');
      const cwd = fields.shift(), argv = fields.slice(0, -1);
      if (args.length > 128 * 1024 || fields.at(-1) !== '' || !names.has(argv[0]) ||
          absolute('/', cwd) !== cwd || (cwd !== workspace && !cwd.startsWith(workspace + '/')))
        throw Error('Invalid Wanix compiler arguments.');
      inputs = null;
      outputs = new Map();
      const result = await trace.call({argv, cwd});
      if (workspaceError) throw workspaceError;
      if (outputs.size && !result.exitCode) await fs.writeFile(request + '/outputs.tar', tar([...outputs]));
      await fs.writeFile(request + '/stdout', result.stdout ?? '');
      await fs.writeFile(request + '/stderr', result.stderr ?? '');
      await fs.remove(shared + 'request');
      await fs.writeFile(request + '/reply', result.exitCode + '\n');
    }
    await delay();
  }
}

async function configure(input, runtime, target, port) {
  const log = line => port.postMessage({kind:'log', line});
  log('Loading the Wanix Linux image and build tools.');
  const [system, profile] = await Promise.all([
    guest(runtime), fetchBytes('alpine/profile.json').then(bytes => JSON.parse(decoder.decode(bytes))),
  ]);
  return planner(system.fs, system.vm, input, target, profile, log);
}

addEventListener('message', async function start(event) {
  if (event.origin !== location.origin || event.source !== parent || event.data?.kind !== 'configure' || !event.ports[0]) return;
  removeEventListener('message', start);
  const port = event.ports[0];
  try {
    const {workflow, snapshot} = await configure(event.data.input, event.data.runtime, event.data.target, port);
    port.postMessage({kind:'configured', workflow, snapshot}, [snapshot.buffer]);
  } catch (error) {
    port.postMessage({kind:'error', error:errorText(error)});
  }
});
